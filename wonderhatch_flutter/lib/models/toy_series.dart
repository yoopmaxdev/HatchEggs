ToySeries seriesById(ToySeriesId id) =>
    kToySeriesList.firstWhere((s) => s.id == id);

ToyDefinition? toyById(String id) {
  for (final series in kToySeriesList) {
    for (final toy in series.toys) {
      if (toy.id == id) return toy;
    }
  }
  return null;
}

List<ToyDefinition> get kAllToys =>
    kToySeriesList.expand((s) => s.toys).toList(growable: false);
