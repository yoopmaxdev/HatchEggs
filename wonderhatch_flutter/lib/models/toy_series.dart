enum ToyRarity {
  common,
  rare,
  epic,
}

class ToySeries {
  final ToySeriesId id;
  final String name;
  final IconData icon;
  final Color primaryColor;
  final Color secondaryColor;
  final List<ToyDefinition> toys;

  const ToySeries({
    required this.id,
    required this.name,
    required this.icon,
    required this.primaryColor,
    required this.secondaryColor,
    required this.toys,
  });
}

class ToyDefinition {
  final String id;
  final String name;
  final ToySeriesId seriesId;
  final Color defaultColor;
  final Color accentColor;
  final ToyRarity rarity;
